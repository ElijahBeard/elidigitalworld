    <h1>How to Make a Patty Melt in 5 Simple Steps</h1>
    <p>This is a step by step guide on how to make a patty melt at home.
        It's a delicious sandwich for a quick yet indulgent lunch.
    </p>
    <p>Note: All ingredients can be swapped for plant-based options (mayos, cheeses, meats).
        If you would like to see vegan recipie guides in the future, please leave a comment on my home page!
    </p>
    <h3>Step 1 : Toast the Bread</h3>
    <p>For my patty melt I went with a school lunch style grilled cheese approach.
    First put some olive oil on a sheet pan. Then, put the white bread down on the pan.
    </p>
    <img src="/blog/pattymelt/0.JPG" alt="">
    <figure>Note: White sandwhich bread.</figure>
    <p>Then, assemble the cheese. I cut up pieces from a 1lb cheddar cheese block 
        that I bought from Kroger, but you can use any cheese you want. Assemble 
        the pieces on one piece of bread, then close it up.
    </p>
    <div class="dua">
        <img src="/blog/pattymelt/1.JPG" alt="">
        <img src="/blog/pattymelt/2.JPG" alt="">
    </div>
    <p>Slap it in the oven at 375 degrees for about 10 minutes,
        flipping halfway through. When you flip it you want to make sure to use
        a thin spatula so that you can get any of the crispy cheese bits still on the bread.
    </p>
    <div class="dua">
        <img src="/blog/pattymelt/7.JPG" alt="">
        <img src="/blog/pattymelt/8.JPG" alt="">
    </div>
    <h3>Step 2 : Prepare The Sauce</h3>
    <p>This step can be done while you're waiting for the bread to toast and the cheese
        to melt. You'll need these ingredients:
    </p>
    <ul>
        <li>Mayo</li>
        <li>Mustard</li>
        <li>Spicy Pickles</li>
        <li>Worcestershire Sauce</li>
        <li>Salt & Pepper</li>
    </ul>
    <p>Simply chop the pickles into small pieces, and mix them in with
        a guesstimated amount of each other ingredients. Ya know a squirta this a squirta that...
    </p>
    <div class="dua">
        <img src="/blog/pattymelt/3.JPG" alt="">
        <img src="/blog/pattymelt/4.JPG" alt="">
    </div>
    <div class="dua">
        <img src="/blog/pattymelt/5.JPG" alt="">
        <img src="/blog/pattymelt/6.JPG" alt="">
    </div>
    <h3>Step 3 : Cooking the Meat</h3>
    <p>You can use any ground meat or plant-based alternative you want. In my example
        I used 70/30 ground beef from the store. Shape it into a large square shape
        and get it pretty thin. Then, season the patty with salt and pepper.
    </p>
    <img src="/blog/pattymelt/12.JPG" alt="">
    <p>Get your pan nice and hot with just a minimal amount of oil. Once the oil starts wisping smoke, slam that patty down.</p>
    <img src="/blog/pattymelt/13.JPG" alt="">
    <p>Cook it for a few minutes to get a nice crust and flip it over. A minute on that side and then were gonna move into the assembly phase.</p>
    <h3>Step 4 : Assembly</h3>
    <p>You're in the home stretch. And I am so proud of you for making it this far. First, open up that grilled cheese.</p>
    <div class="dua">
        <img src="/blog/pattymelt/9.JPG" alt="">
        <img src="/blog/pattymelt/10.JPG" alt="">
    </div>
        <figure>Looks rlly good :0</figure>
    <p>Now slap that sauce on there</p>
    <img src="/blog/pattymelt/11.JPG" alt="">
    <p>Now the patty...</p>
    <img src="/blog/pattymelt/14.JPG" alt="">
    <p>And you're done! There is only one step left....</p>
    <h3>Step 5: Enjoy</h3>
    <p>I am eating mine with a cherry pepsi, and I got that sauce
        on the side for dipping. Enjoy!
    </p>
